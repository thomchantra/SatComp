#!/usr/bin/env python3
"""Generates satcomp-plugin/src/params.rs from the JSFX slider table. Run from rust/: python3 tools/gen_params.py"""
# (slider n, field, display name, kind, min, max, default, step, unit)
P = []
def add(n, field, name, kind, mn, mx, df, step=None, unit=""):
    P.append((n, field, name, kind, mn, mx, df, step, unit))

add(1, "shape", "Shape", "int", 0, 14, 0)
add(2, "drive", "Drive", "f", 0, 100, 25, 0.1, " %")
add(3, "bias", "Bias", "f", -100, 100, 0, 0.1, " %")
add(4, "sat_hp", "Sat HP", "f", 20, 2000, 20, 1, " Hz")
add(5, "sat_lp", "Sat LP", "f", 1000, 20000, 20000, 1, " Hz")
add(6, "tone", "Tone", "f", 1000, 20000, 20000, 1, " Hz")
add(7, "os", "Oversampling", "int", 0, 2, 0)
add(8, "thresh", "Thresh", "f", -40, 0, -18, 0.1, " dB")
add(9, "ratio", "Ratio", "f", 1, 20, 4, 0.1)
add(10, "attack", "Attack", "f", 0.05, 100, 10, 0.01, " ms")
add(11, "release", "Release", "f", 5, 2000, 150, 1, " ms")
add(12, "speed", "Speed", "f", 0, 100, 50, 1, " %")
add(13, "knee", "Knee", "f", 0, 24, 6, 0.1, " dB")
add(14, "knee_shape", "Knee Shape", "f", 0, 100, 0, 1, " %")
add(15, "detector", "Peak>RMS", "f", 0, 100, 30, 1, " %")
add(16, "det_hp", "Low Cut", "f", 0, 400, 0, 1, " Hz")
add(18, "ff_fb", "FF>FB", "f", 0, 100, 0, 1, " %")
add(19, "gr_dist", "GR Dist", "f", 0, 100, 0, 1, " %")
add(20, "makeup", "Makeup", "f", 0, 24, 0, 0.1, " dB")
add(21, "mix", "Mix", "f", 0, 100, 100, 1, " %")
add(22, "out_gain", "Out Gain", "f", -24, 12, 0, 0.1, " dB")
add(23, "gain_match", "Gain Match", "bool", 0, 1, 0)
add(25, "sat_mix", "Sat Mix", "f", 0, 100, 100, 1, " %")
add(26, "bypass", "Bypass", "bool", 0, 1, 0)
add(27, "sat_out", "Sat Out", "f", -24, 12, 0, 0.1, " dB")
for st, (stn, base) in enumerate([("Pre", 29), ("Post", 44)]):
    sp = stn.lower()
    for b in range(3):
        n = base + b * 4
        df = [80, 200, 6000][b]
        add(n, f"{sp}_b{b+1}_type", f"{stn} B{b+1} Type", "int", 0, 2, 0)
        add(n + 1, f"{sp}_b{b+1}_freq", f"{stn} B{b+1} Freq", "f", 20, 20000, df, 1, " Hz")
        add(n + 2, f"{sp}_b{b+1}_gain", f"{stn} B{b+1} Gain", "f", -18, 18, 0, 0.1, " dB")
        add(n + 3, f"{sp}_b{b+1}_q", f"{stn} B{b+1} Q", "f", 0.1, 10, 0.5, 0.01)
    add(base + 12, f"{sp}_tilt", f"{stn} Tilt", "f", -12, 12, 0, 0.1, " dB")
    add(base + 13, f"{sp}_pivot", f"{stn} Pivot", "f", 20, 20000, 600, 1, " Hz")
    add(base + 14, f"{sp}_out_gain", f"{stn} Out Gain", "f", -12, 12, 0, 0.1, " dB")
add(59, "lookahead", "Lookahead", "f", 0, 10, 0, 0.1, " ms")
add(60, "eq_pre_bypass", "EQ Pre Bypass", "bool", 0, 1, 0)
add(61, "eq_post_bypass", "EQ Post Bypass", "bool", 0, 1, 0)
add(62, "eq_module_bypass", "EQ Module Bypass", "bool", 0, 1, 0)

def f(x):
    s = repr(float(x))
    return s

o = []
o.append("// GENERATED by tools/gen_params.py from the JSFX slider table. Do not edit by hand.\n")
o.append("use nih_plug::prelude::*;\nuse nih_plug_egui::EguiState;\nuse satcomp_dsp::shapers::Curve;\nuse satcomp_dsp::{EqBandParams, EqStageParams};\nuse std::sync::atomic::AtomicI32;\nuse std::sync::Arc;\n")
o.append("/// (slider number, id, min, max, default, step) for every parameter; slider numbers follow SatComp.jsfx.")
o.append("pub const TABLE: &[(usize, &str, f32, f32, f32)] = &[")
for n, fl, name, k, mn, mx, df, st, u in P:
    o.append(f'    ({n}, "{fl}", {f(mn)}, {f(mx)}, {f(df)}),')
o.append("];\n")
o.append("#[derive(Params)]\npub struct SatCompParams {")
o.append('    #[persist = "editor-state"]\n    pub editor_state: Arc<EguiState>,')
o.append('    /// Colour scheme index (0 Black, 1 White, 2.. see palette table); UI-only, saved with the project.\n    #[persist = "palette"]\n    pub palette: Arc<AtomicI32>,')
o.append('    /// Name of the last loaded/saved preset (display only).\n    #[persist = "preset-name"]\n    pub preset_name: Arc<parking_lot::Mutex<String>>,')
o.append('    /// User-drawn waveshaper curve (points on [-1,1]^2, shaper 14 "Custom"); saved with the project and presets.\n    #[persist = "custom-curve"]\n    pub custom_curve: Arc<parking_lot::Mutex<Vec<(f32, f32)>>>,')
o.append('    /// Out-stage gain-match trim (dB) written by the 3 s measurement; saved with the project.\n    #[persist = "match-trim"]\n    pub match_trim: Arc<AtomicF32>,')
for n, fl, name, k, mn, mx, df, st, u in P:
    o.append(f'    #[id = "{fl}"]\n    pub {fl}: {"IntParam" if k=="int" else "BoolParam" if k=="bool" else "FloatParam"},')
o.append("}\n")
o.append("impl Default for SatCompParams {\n    fn default() -> Self {\n        Self {")
o.append("            editor_state: EguiState::from_size(700, 420),")
o.append("            palette: Arc::new(AtomicI32::new(0)),")
o.append("            preset_name: Arc::new(parking_lot::Mutex::new(String::new())),")
o.append("            custom_curve: Arc::new(parking_lot::Mutex::new(vec![(-1.0, -1.0), (1.0, 1.0)])),")
o.append("            match_trim: Arc::new(AtomicF32::new(0.0)),")
for n, fl, name, k, mn, mx, df, st, u in P:
    if k == "int":
        o.append(f'            {fl}: IntParam::new("{name}", {int(df)}, IntRange::Linear {{ min: {int(mn)}, max: {int(mx)} }}),')
    elif k == "bool":
        o.append(f'            {fl}: BoolParam::new("{name}", {"true" if df else "false"}),')
    else:
        s = f'            {fl}: FloatParam::new("{name}", {f(df)}, FloatRange::Linear {{ min: {f(mn)}, max: {f(mx)} }})'
        if u: s += f'.with_unit("{u}")'
        if st: s += f'.with_step_size({f(st)})'
        o.append(s + ",")
o.append("        }\n    }\n}\n")
o.append("impl SatCompParams {")
o.append("    /// Sanitised copy of the persisted custom curve (the UI holds this lock only for a point edit).\n    pub fn curve_snapshot(&self) -> Curve {\n        Curve::from_points(&self.custom_curve.lock())\n    }\n")
o.append("    /// Snapshot for the DSP engine.\n    pub fn to_dsp(&self) -> satcomp_dsp::Params {")
o.append("        let stage = |bands: [(&IntParam, &FloatParam, &FloatParam, &FloatParam); 3], tilt: &FloatParam, pivot: &FloatParam, og: &FloatParam| EqStageParams {")
o.append("            bands: [0, 1, 2].map(|i| EqBandParams { ty: bands[i].0.value() as f64, freq: bands[i].1.value() as f64, gain: bands[i].2.value() as f64, q: bands[i].3.value() as f64 }),")
o.append("            tilt: tilt.value() as f64, pivot: pivot.value() as f64, out_gain: og.value() as f64,\n        };")
o.append("        satcomp_dsp::Params {")
o.append("            shape: self.shape.value(), curve: self.curve_snapshot(), drive: self.drive.value() as f64, bias: self.bias.value() as f64,")
o.append("            sat_hp: self.sat_hp.value() as f64, sat_lp: self.sat_lp.value() as f64, tone: self.tone.value() as f64, os: self.os.value(),")
o.append("            thresh: self.thresh.value() as f64, ratio: self.ratio.value() as f64, attack: self.attack.value() as f64,")
o.append("            release: self.release.value() as f64, speed: self.speed.value() as f64, knee: self.knee.value() as f64,")
o.append("            knee_shape: self.knee_shape.value() as f64, detector: self.detector.value() as f64, det_hp: self.det_hp.value() as f64,")
o.append("            ff_fb: self.ff_fb.value() as f64, gr_dist: self.gr_dist.value() as f64, makeup: self.makeup.value() as f64,")
o.append("            mix: self.mix.value() as f64, out_gain: self.out_gain.value() as f64, gain_match: self.gain_match.value(),")
o.append("            sat_mix: self.sat_mix.value() as f64, bypass: self.bypass.value(), sat_out: self.sat_out.value() as f64,")
def stage_expr(sp):
    bs = ", ".join(f"(&self.{sp}_b{b}_type, &self.{sp}_b{b}_freq, &self.{sp}_b{b}_gain, &self.{sp}_b{b}_q)" for b in (1,2,3))
    return f"stage([{bs}], &self.{sp}_tilt, &self.{sp}_pivot, &self.{sp}_out_gain)"
o.append(f"            eq: [{stage_expr('pre')}, {stage_expr('post')}],")
o.append("            lookahead_ms: self.lookahead.value() as f64, eq_pre_bypass: self.eq_pre_bypass.value(),")
o.append("            eq_post_bypass: self.eq_post_bypass.value(), eq_module_bypass: self.eq_module_bypass.value(),")
o.append("        }\n    }\n")
o.append("    /// Parameter by JSFX slider number (UI addressing).\n    pub fn ptr(&self, n: usize) -> Option<ParamPtr> {\n        Some(match n {")
for n, fl, *_ in P:
    o.append(f"            {n} => self.{fl}.as_ptr(),")
o.append("            _ => return None,\n        })\n    }\n}")
open("satcomp-plugin/src/params.rs", "w").write("\n".join(o) + "\n")
print(len(P), "params")
