#!/usr/bin/env python3
"""Adds `from_values` and `to_dsp_over` to the plug-ins' generated params.rs (run from rust/ after any gen_*params.py:
python3 tools/gen_shadow.py). Idempotent: the block lives between two marker comments and is replaced.

Why: nih-plug applies a UI write to a parameter only inside a later audio callback, so the plain parameters trail the mouse by a host
block or more. The sliders show the editor's pending value (satcomp-ui kit), and the viewports (waveshaper plot, EQ, crossover) are
drawn from `to_dsp_over`: a snapshot of a second, throw-away parameter set built by `from_values`, whose values are the current ones
with the pending writes on top. nih-plug has no public setter for a parameter, but its constructors take the value, so the set is
rebuilt from them (only while a write is pending).
"""
import re, sys

BEGIN = "    // --- shadow (generated by tools/gen_shadow.py, do not edit) ---\n"
END = "    // --- end shadow ---\n"

def process(path):
    t = open(path).read()
    if BEGIN in t:  # replace an earlier block
        a = t.index(BEGIN); b = t.index(END) + len(END)
        t = t[:a] + t[b:]
    slots = {name: int(n) for n, name in re.findall(r"^\s+(\d+) => self\.(\w+)\.as_ptr\(\),", t, re.M)}
    m = re.search(r"    pub fn from_defaults\(d: Option<satcomp_ui::appearance::Defaults>\) -> Self \{\n(.*?)\n    \}\n", t, re.S)
    assert m, path + ": no from_defaults"
    body = m.group(1)
    out = []
    n_conv = 0
    for line in body.split("\n"):
        mm = re.match(r"^(\s+)(\w+): (FloatParam|IntParam|BoolParam)::new\(\"([^\"]*)\", ([^,)]+)(.*)$", line)
        if not mm:
            out.append(line)
            continue
        ind, fld, kind, name, default, rest = mm.groups()
        real = f"self.{fld}.value()"
        o = f"over({slots[fld]})" if fld in slots else None
        if kind == "FloatParam":
            val = f"{o}.unwrap_or({real})" if o else real
        elif kind == "IntParam":
            val = f"{o}.map(|v| (v + 0.5).floor() as i32).unwrap_or({real})" if o else real
        else:
            val = f"{o}.map(|v| v > 0.5).unwrap_or({real})" if o else real
        out.append(f"{ind}{fld}: {kind}::new(\"{name}\", {val}{rest}")
        n_conv += 1
    fv = ("    /// A throw-away parameter set holding this one's current values with `over(slot)` (the editor's pending writes) on top.\n"
          "    pub fn from_values(&self, over: &dyn Fn(usize) -> Option<f32>) -> Self {\n"
          "        let d: Option<satcomp_ui::appearance::Defaults> = None;\n" + "\n".join(out) + "\n    }\n")
    m2 = re.search(r"    pub fn to_dsp\(&self\) -> (.+?) \{\n(.*?)\n    \}\n", t, re.S)
    assert m2, path + ": no to_dsp"
    ret, tb = m2.groups()
    assert "self.to_dsp_with(" in tb
    tb = tb.replace("self.to_dsp_with(", "shadow.to_dsp_with(")
    td = ("    /// The `to_dsp` snapshot with `over(slot)` (the editor's pending writes) applied: what the viewports are drawn from, so they\n"
          "    /// follow the mouse and not the host's later answer. Costs a rebuilt parameter set, so use it only while a write is pending.\n"
          f"    pub fn to_dsp_over(&self, over: &dyn Fn(usize) -> Option<f32>) -> {ret} {{\n"
          "        let shadow = self.from_values(over);\n" + tb + "\n    }\n")
    block = BEGIN + fv + "\n" + td + END + "\n"
    c = t.index("    /// Audio-thread snapshot")
    t = t[:c] + block + t[c:]
    open(path, "w").write(t)
    print(f"{path}: {n_conv} parameters, {len(slots)} slots")

for pl in ["satcomp", "satxcomp", "satlim", "satdiff"]:
    process(f"{pl}-plugin/src/params.rs")
