#!/usr/bin/env python3
"""Generates satlim-plugin/src/params.rs (SatLim parameters). Run from rust/: python3 tools/gen_lparams.py

Parameter ids are permanent once released. Slot numbers are the UI's addressing scheme; the sat module keeps SatComp's slot numbers (1-7, 25, 27, bypass 26, out gain 22) so the shared sat UI code addresses the same cells.
"""
P = []  # (slot, id, display name, kind, min, max, default, step, unit)
def add(n, i, name, kind, mn, mx, df, step=None, unit=""):
    P.append((n, i, name, kind, mn, mx, df, step, unit))

# SAT (the SatComp saturator module)
add(1, "shape", "Shape", "int", 0, 14, 0)
add(2, "drive", "Drive", "f", 0, 100, 0, 0.1, " %")
add(3, "bias", "Bias", "f", -100, 100, 0, 0.1, " %")
add(4, "sat_hp", "Sat HP", "f", 20, 2000, 20, 1, " Hz")
add(5, "sat_lp", "Sat LP", "f", 200, 20000, 20000, 1, " Hz")
add(6, "tone", "Tone", "f", 1000, 20000, 20000, 1, " Hz")
add(7, "os", "Oversampling", "int", 0, 3, 0)          # x1 x2 x4 x8: saturator and clipper
add(25, "sat_mix", "Sat Mix", "f", 0, 100, 100, 1, " %")
add(27, "sat_gain", "Sat Gain", "f", -24, 12, 0, 0.1, " dB")
# LIMITER
add(12, "lookahead", "Lookahead", "bool", 0, 1, 1)    # off = zero latency, sample peak, instant attack
add(8, "ceiling", "Ceiling", "f", -24, 0, -0.3, 0.1, " dB")
add(9, "threshold", "Threshold", "f", -30, 0, 0, 0.1, " dB")
add(10, "release", "Release", "f", 15, 80, 80, 1, " ms")
add(11, "clip", "Grab", "f", 0, 100, 0, 1, " %")
add(22, "out_gain", "Out Gain", "f", -24, 12, 0, 0.1, " dB")
add(26, "bypass", "Bypass", "bool", 0, 1, 0)

def f(x):
    return repr(float(x))

o = []
o.append("// GENERATED by tools/gen_lparams.py. Do not edit by hand.\n")
o.append("use nih_plug::prelude::*;\nuse nih_plug_egui::EguiState;\nuse satcomp_dsp::shapers::{asym_from, Curve, SHAPER_COUNT};\nuse satlim_dsp::LimParams;\nuse std::sync::atomic::{AtomicBool, AtomicI32};\nuse std::sync::Arc;\n")
o.append("/// Highest UI slot number + 1.\npub const SLOTS: usize = %d;\n" % (max(p[0] for p in P) + 1))
o.append("/// (slot number, id, min, max, default) for every parameter.")
o.append("pub const TABLE: &[(usize, &str, f32, f32, f32)] = &[")
for n, i, name, k, mn, mx, df, st, u in P:
    o.append(f'    ({n}, "{i}", {f(mn)}, {f(mx)}, {f(df)}),')
o.append("];\n")
o.append("#[derive(Params)]\npub struct SatLimParams {")
o.append('    #[persist = "editor-state"]\n    pub editor_state: Arc<EguiState>,')
o.append('    /// Colour scheme index in the palette table (-1 = not set yet); UI-only, saved with the project.\n    #[persist = "palette-v2"]\n    pub palette_v2: Arc<AtomicI32>,')
o.append('    /// Light mode (the inverted palette of the scheme); UI-only, saved with the project.\n    #[persist = "light-mode"]\n    pub light: Arc<AtomicBool>,')
o.append('    /// Scope fill: true = solid UI-colour bars, false = outline stroke along the peaks; UI-only.\n    #[persist = "fft-solid"]\n    pub fft_solid: Arc<AtomicBool>,')
o.append('    /// UI font index (see `satcomp_ui::canvas::FONT_NAMES`); UI-only, saved with the project.\n    #[persist = "ui-font"]\n    pub font: Arc<AtomicI32>,')
o.append('    /// Active user colour theme (`name|` + 18 hex digits) so a project keeps its look on a machine without the themes file.\n    #[persist = "custom-theme"]\n    pub custom_theme: Arc<parking_lot::Mutex<String>>,')
o.append('    /// Packed scope view settings (see gui/ui/scope.rs); UI-only, saved with the project.\n    #[persist = "scope-v3"]\n    pub scope: Arc<AtomicI32>,')
o.append('    /// Name of the last loaded/saved preset (display only).\n    #[persist = "preset-name"]\n    pub preset_name: Arc<parking_lot::Mutex<String>>,')
o.append('    /// User-drawn waveshaper curve (points on [-1,1]^2, shaper 14 "Custom"); saved with the project and presets.\n    #[persist = "custom-curve"]\n    pub custom_curve: Arc<parking_lot::Mutex<Vec<(f32, f32)>>>,')
o.append('    /// ASYM per waveshaper (0..100 %, index = shaper); saved with the project and presets (absent = all 100 %).\n    #[persist = "asym"]\n    pub asym: Arc<parking_lot::Mutex<Vec<f32>>>,')
for n, i, name, k, mn, mx, df, st, u in P:
    o.append(f'    #[id = "{i}"]\n    pub {i}: {"IntParam" if k=="int" else "BoolParam" if k=="bool" else "FloatParam"},')
o.append("}\n")
o.append("impl Default for SatLimParams {\n    fn default() -> Self {\n        Self {")
o.append("            editor_state: EguiState::from_size(340, 504),")
o.append("            palette_v2: Arc::new(AtomicI32::new(-1)),")
o.append("            light: Arc::new(AtomicBool::new(false)),")
o.append("            font: Arc::new(AtomicI32::new(0)),")
o.append("            fft_solid: Arc::new(AtomicBool::new(true)),")
o.append("            scope: Arc::new(AtomicI32::new((5 << 4) | (2 << 8))),")
o.append("            custom_theme: Arc::new(parking_lot::Mutex::new(String::new())),")
o.append("            preset_name: Arc::new(parking_lot::Mutex::new(String::new())),")
o.append("            custom_curve: Arc::new(parking_lot::Mutex::new(vec![(-1.0, -1.0), (1.0, 1.0)])),")
o.append("            asym: Arc::new(parking_lot::Mutex::new(Vec::new())),")
for n, i, name, k, mn, mx, df, st, u in P:
    if k == "int":
        o.append(f'            {i}: IntParam::new("{name}", {int(df)}, IntRange::Linear {{ min: {int(mn)}, max: {int(mx)} }}),')
    elif k == "bool":
        o.append(f'            {i}: BoolParam::new("{name}", {"true" if df else "false"}),')
    else:
        s = f'            {i}: FloatParam::new("{name}", {f(df)}, FloatRange::Linear {{ min: {f(mn)}, max: {f(mx)} }})'
        if u: s += f'.with_unit("{u}")'
        if st: s += f'.with_step_size({f(st)})'
        o.append(s + ",")
o.append("        }\n    }\n}\n")
o.append("impl SatLimParams {")
o.append("    /// Sanitised copy of the persisted custom curve (the UI holds this lock only for a point edit).\n    pub fn curve_snapshot(&self) -> Curve {\n        Curve::from_points(&self.custom_curve.lock())\n    }\n")
o.append("    /// ASYM per shaper, sanitised (short / missing = 100 %).\n    pub fn asym_snapshot(&self) -> [f64; SHAPER_COUNT] {\n        asym_from(&self.asym.lock())\n    }\n")
o.append("    /// Snapshot for the DSP engine (UI side: may wait briefly for the curve lock).\n    pub fn to_dsp(&self) -> LimParams {\n        self.to_dsp_with(self.curve_snapshot(), self.asym_snapshot())\n    }\n")
o.append("    /// Audio-thread snapshot: never blocks on the curve lock. While the UI holds it the previous curve is reused.\n    pub fn to_dsp_rt(&self, last: &mut Curve, last_asym: &mut [f64; SHAPER_COUNT]) -> LimParams {\n        if let Some(g) = self.custom_curve.try_lock() {\n            *last = Curve::from_points(&g);\n        }\n        if let Some(g) = self.asym.try_lock() {\n            *last_asym = asym_from(&g);\n        }\n        self.to_dsp_with(*last, *last_asym)\n    }\n")
o.append("    fn to_dsp_with(&self, curve: Curve, asym: [f64; SHAPER_COUNT]) -> LimParams {")
o.append("        LimParams {")
o.append("            shape: self.shape.value(), curve, asym, drive: self.drive.value() as f64, bias: self.bias.value() as f64,")
o.append("            sat_hp: self.sat_hp.value() as f64, sat_lp: self.sat_lp.value() as f64, tone: self.tone.value() as f64,")
o.append("            sat_mix: self.sat_mix.value() as f64, sat_gain: self.sat_gain.value() as f64, os: self.os.value(),")
o.append("            lookahead: self.lookahead.value(), ceiling: self.ceiling.value() as f64, threshold: self.threshold.value() as f64,")
o.append("            release: self.release.value() as f64, clip: self.clip.value() as f64, out_gain: self.out_gain.value() as f64,")
o.append("            bypass: self.bypass.value(),")
o.append("        }\n    }\n")
o.append("    /// Parameter by slot number (UI addressing).\n    pub fn ptr(&self, n: usize) -> Option<ParamPtr> {\n        Some(match n {")
for n, i, *_ in P:
    o.append(f"            {n} => self.{i}.as_ptr(),")
o.append("            _ => return None,\n        })\n    }\n}")
import os
os.makedirs("satlim-plugin/src", exist_ok=True)
open("satlim-plugin/src/params.rs", "w").write("\n".join(o) + "\n")
print(len(P), "params")
