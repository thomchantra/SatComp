#!/usr/bin/env python3
"""Plug-in icons: docs/internal/plugintitles/<NAME>.svg (the lockup: frame, then the icon as filled paths, then the wordmark)
-> rust/satcomp-ui/src/logo_art.rs, each filled shape as convex quads in the SVG's 30 x 30 design units.

    python3 rust/tools/gen_logo.py

Only the straight-line paths before the first curve are used (the icon); the frame is the plate the UI draws itself.
Rings and L-shapes are cut into overlapping quads (overlap keeps the anti-aliased seams invisible)."""
import re, sys, pathlib
root = pathlib.Path(__file__).resolve().parents[2]
src = root / "docs/internal/plugintitles"
PLUGINS = [("SATCOMP", "SatComp"), ("SATXCOMP", "SatXComp"), ("SATLIM", "SatLim"), ("SATDIFF", "SatDiff")]

def subpaths(d):
    out, cur, x, y = [], None, 0.0, 0.0
    for c, args in re.findall(r"([MLHVZ])([^MLHVZ]*)", d):
        n = [float(v) for v in re.findall(r"-?\d*\.?\d+", args)]
        if c == "M": x, y = n[0], n[1]; cur = [(x, y)]; out.append(cur)
        elif c == "L": x, y = n[0], n[1]; cur.append((x, y))
        elif c == "H": x = n[0]; cur.append((x, y))
        elif c == "V": y = n[0]; cur.append((x, y))
    return [p[:-1] if p[0] == p[-1] else p for p in out]

def bbox(p):
    xs, ys = [q[0] for q in p], [q[1] for q in p]
    return min(xs), min(ys), max(xs), max(ys)

def rect(x0, y0, x1, y1): return [(x0, y0), (x1, y0), (x1, y1), (x0, y1)]

def axis_aligned(p): return all(abs(a[0]-b[0]) < 1e-3 or abs(a[1]-b[1]) < 1e-3 for a, b in zip(p, p[1:]+p[:1]))

def cut_l(p):
    """axis-aligned L (6 corners) -> two overlapping rects: the two arms, each spanning the full extent on its axis.
    The reflex corner is the vertex at the middle value on both axes; the elbow is the bbox corner nearest to it."""
    xs, ys = sorted(set(round(q[0], 4) for q in p)), sorted(set(round(q[1], 4) for q in p))
    if len(xs) != 3 or len(ys) != 3: sys.exit("unsupported L: %r" % (p,))
    (x0, x1, x2), (y0, y1, y2) = xs, ys
    elbow_left = abs(x1 - x0) < abs(x1 - x2)
    elbow_top = abs(y1 - y0) < abs(y1 - y2)
    th_x = (x0, x1) if elbow_left else (x1, x2)
    th_y = (y0, y1) if elbow_top else (y1, y2)
    return [rect(x0, th_y[0], x2, th_y[1]), rect(th_x[0], y0, th_x[1], y2)]

def cut(sp):
    """all subpaths of one <path> -> convex pieces"""
    if len(sp) == 2 and len(sp[0]) == 4 and len(sp[1]) == 4 and all(axis_aligned(s) for s in sp):   # ring
        (a0, b0, a1, b1), (c0, d0, c1, d1) = bbox(sp[0]), bbox(sp[1])
        if c0 > a0 and a1 > c1:
            return [rect(a0, b0, a1, d0), rect(a0, d1, a1, b1), rect(a0, b0, c0, b1), rect(c1, b0, a1, b1)]
    out = []
    for p in sp:
        if len(p) == 4: out.append(p)
        elif len(p) == 6 and axis_aligned(p): out += cut_l(p)
        else: sys.exit("unsupported shape: %r" % (p,))
    return out

def fmt(v): return ("%.4f" % v).rstrip("0").rstrip(".")

def lim_from_comp(comp):
    """SatLim's own SVG is not symmetric (its top-left bracket and its box sit 0.1 to 0.3 units off the other corners, so at 100 %
    the corners land on different pixel phases). SatLim's icon is SatComp's box plus four brackets, so build it that way:
    SatComp's box and its bottom-left bracket, mirrored into every corner."""
    box, bl = comp[:4], comp[6:8]
    out = list(box)
    for mx in (False, True):
        for my in (False, True):
            for q in bl:
                out.append([(30 - x if mx else x, 30 - y if my else y) for x, y in q])
    return out

lines = ["//! GENERATED by rust/tools/gen_logo.py from docs/internal/plugintitles/*.svg: do not edit.",
         "//! Each plug-in icon as convex quads (x0, y0 .. x3, y3) in the SVG's 30 x 30 design units (the plate is 20 pt: scale 2/3).", ""]
names = []
comp_quads = None
for stem, disp in PLUGINS:
    svg = (src / (stem + ".svg")).read_text()
    paths = re.findall(r'<path d="([^"]+)"', svg)
    quads = []
    for d in paths:
        if "C" in d: break
        quads += cut(subpaths(d))
    if stem == "SATCOMP": comp_quads = quads
    if stem == "SATLIM": quads = lim_from_comp(comp_quads)
    const = "LOGO_" + stem[3:]
    names.append(const)
    lines.append("pub const %s: [[f32; 8]; %d] = [" % (const, len(quads)))
    for q in quads:
        lines.append("    [" + ", ".join(fmt(v) for p in q for v in p) + "],")
    lines.append("];\n")
(root / "rust/satcomp-ui/src/logo_art.rs").write_text("\n".join(lines))
print("wrote logo_art.rs:", ", ".join(names))
