#!/usr/bin/env python3
"""Generates satxcomp-plugin/src/params.rs (SatXComp parameters). Run from rust/: python3 tools/gen_xparams.py

Parameter ids are permanent once released. Slot numbers are the UI's addressing scheme (like SatComp's slider numbers):
globals 1-9 (x3 is 9), band b (lo, ml, mh, hi) starts at 10 + 24*b (to 105), crossover slopes 106-108, sidechain 110-114,
EQ band i starts at 120 + 5*i, EQ globals 145-149, limiter 150, band RANGE (upward compression) 160-163 (the band's UP switch is offset 23).
"""
P = []  # (slot, id, display name, kind, min, max, default, step, unit)
def add(n, i, name, kind, mn, mx, df, step=None, unit=""):
    P.append((n, i, name, kind, mn, mx, df, step, unit))

add(1, "x1", "X-Over 1", "f", 20, 2000, 150, 1, " Hz")
add(2, "x2", "X-Over 2", "f", 200, 20000, 800, 1, " Hz")
add(9, "x3", "X-Over 3", "f", 200, 20000, 3500, 1, " Hz")
add(3, "os", "Sat Oversampling", "int", 0, 2, 0)
add(4, "lookahead", "Lookahead", "f", 0, 10, 0, 0.1, " ms")
add(5, "mix", "Mix", "f", 0, 100, 100, 1, " %")
add(6, "out_gain", "Out Gain", "f", -24, 12, 0, 0.1, " dB")
add(7, "gain_match", "Gain Match", "bool", 0, 1, 0)
add(8, "bypass", "Bypass", "bool", 0, 1, 0)
# crossover slope per split: 0 = 12, 1 = 24, 2 = 48, 3 = 96 dB/oct (slots 106-108)
add(106, "x1_slope", "X-Slope 1", "int", 0, 3, 1)
add(107, "x2_slope", "X-Slope 2", "int", 0, 3, 1)
add(108, "x3_slope", "X-Slope 3", "int", 0, 3, 1)
# sidechain: on, key gain / HP / LP (global, applied before the key is split into bands) and KEY MIX (slots 110-114)
add(110, "sc_on", "Sidechain", "bool", 0, 1, 0)
add(111, "sc_gain", "SC Gain", "f", -24, 24, 0, 0.1, " dB")
add(112, "sc_hp", "SC HP", "f", 20, 2000, 20, 1, " Hz")
add(113, "sc_lp", "SC LP", "f", 200, 20000, 20000, 1, " Hz")
add(114, "sc_mix", "Key Mix", "f", 0, 100, 100, 1, " %")

BANDS = [("lo", "Lo"), ("mid", "ML"), ("mh", "MH"), ("hi", "Hi")]  # ids: "mid" is the low-mid band (it was the 3-band middle one)
BAND_FIELDS = [  # offset, field, name, kind, min, max, default, step, unit
    (0, "on", "On", "bool", 0, 1, 1),
    (1, "solo", "Solo", "bool", 0, 1, 0),
    (2, "delta", "Delta", "bool", 0, 1, 0),
    (3, "shape", "Shape", "int", 0, 14, 0),
    (4, "drive", "Drive", "f", 0, 100, 0, 0.1, " %"),
    (5, "bias", "Bias", "f", -100, 100, 0, 0.1, " %"),
    (6, "tone", "Tone", "f", 1000, 20000, 20000, 1, " Hz"),
    (7, "sat_mix", "Sat Mix", "f", 0, 100, 100, 1, " %"),
    (8, "sat_gain", "Sat Gain", "f", -24, 12, 0, 0.1, " dB"),
    (9, "thresh", "Thresh", "f", -40, 0, 0, 0.1, " dB"),
    (10, "ratio", "Ratio", "f", 1, 20, 4, 0.1),
    (11, "attack", "Attack", "f", 0.05, 100, 10, 0.01, " ms"),
    (12, "release", "Release", "f", 5, 2000, 150, 1, " ms"),
    (13, "speed", "Speed", "f", 0, 100, 50, 1, " %"),
    (14, "knee", "Knee", "f", 0, 24, 6, 0.1, " dB"),
    (15, "knee_shape", "Knee Shape", "f", 0, 100, 0, 1, " %"),
    (16, "detector", "Peak>RMS", "f", 0, 100, 30, 1, " %"),
    (17, "ff_fb", "FF>FB", "f", 0, 100, 0, 1, " %"),
    (18, "gr_dist", "GR Dist", "f", 0, 100, 0, 1, " %"),
    (19, "comp_mix", "Comp Mix", "f", 0, 100, 100, 1, " %"),
    (20, "comp_gain", "Comp Gain", "f", -12, 24, 0, 0.1, " dB"),
    (21, "hp", "HP", "f", 20, 2000, 20, 1, " Hz"),
    (22, "lp", "LP", "f", 200, 20000, 20000, 1, " Hz"),
    (23, "up", "Comp Mode", "int", 0, 2, 0),  # 0 downward, 1 upward (lift below the threshold), 2 both
    (1160, "up_range", "Range", "f", 0, 24, 12, 0.1, " dB"),  # offsets >= 1000 are absolute slots: 160 + band (160-163)
]
for b, (bid, bname) in enumerate(BANDS):
    for fld in BAND_FIELDS:
        off, f, name, kind, mn, mx, df = fld[:7]
        st = fld[7] if len(fld) > 7 else None
        u = fld[8] if len(fld) > 8 else ""
        slot = 10 + 24 * b + off if off < 1000 else off - 1000 + b
        add(slot, f"{bid}_{f}", f"{bname} {name}", kind, mn, mx, df, st, u)

EQ_DEF_TYPE = [1, 2, 2, 2, 1]
EQ_DEF_FREQ = [80, 200, 1000, 5000, 10000]
EQ_DEF_ON = [1, 1, 0, 0, 1]
for i in range(5):
    n = 120 + 5 * i
    add(n, f"eq{i+1}_on", f"EQ{i+1} On", "bool", 0, 1, EQ_DEF_ON[i])
    add(n + 1, f"eq{i+1}_type", f"EQ{i+1} Type", "int", 0, 5, EQ_DEF_TYPE[i])
    add(n + 2, f"eq{i+1}_freq", f"EQ{i+1} Freq", "f", 20, 20000, EQ_DEF_FREQ[i], 1, " Hz")
    add(n + 3, f"eq{i+1}_q", f"EQ{i+1} Q", "f", 0.1, 10, 0.71, 0.01)
    add(n + 4, f"eq{i+1}_gain", f"EQ{i+1} Gain", "f", -18, 18, 0, 0.1, " dB")
add(145, "eq_tilt", "EQ Tilt", "f", -12, 12, 0, 0.1, " dB")
add(146, "eq_pivot", "EQ Pivot", "f", 20, 20000, 600, 1, " Hz")
add(147, "eq_mix", "EQ Mix", "f", 0, 100, 100, 1, " %")
add(148, "eq_gain", "EQ Gain", "f", -12, 12, 0, 0.1, " dB")
add(149, "eq_bypass", "EQ Bypass", "bool", 0, 1, 0)
add(150, "lim_on", "Limiter", "bool", 0, 1, 1)

def f(x):
    return repr(float(x))

o = []
o.append("// GENERATED by tools/gen_xparams.py. Do not edit by hand.\n")
o.append("use nih_plug::prelude::*;\nuse nih_plug_egui::EguiState;\nuse satcomp_dsp::shapers::Curve;\nuse satxcomp_dsp::params::SHAPER_COUNT;\nuse satxcomp_dsp::{BandParams, EqBandParams, EqParams, XParams};\nuse std::sync::atomic::{AtomicBool, AtomicI32};\nuse std::sync::Arc;\n")
o.append("/// Highest UI slot number + 1.\npub const SLOTS: usize = 164;\n")
o.append("/// (slot number, id, min, max, default) for every parameter.")
o.append("pub const TABLE: &[(usize, &str, f32, f32, f32)] = &[")
for n, i, name, k, mn, mx, df, st, u in P:
    o.append(f'    ({n}, "{i}", {f(mn)}, {f(mx)}, {f(df)}),')
o.append("];\n")
o.append("#[derive(Params)]\npub struct SatXCompParams {")
o.append('    #[persist = "editor-state"]\n    pub editor_state: Arc<EguiState>,')
o.append('    /// Colour scheme index (see satcomp-ui palettes; >= 20 = user theme); UI-only.\n    #[persist = "palette-v2"]\n    pub palette_v2: Arc<AtomicI32>,')
o.append('    #[persist = "light-mode"]\n    pub light: Arc<AtomicBool>,')
o.append('    /// Spectrum fill: true = solid UI-colour area under the output, false = outline; UI-only.\n    #[persist = "fft-solid"]\n    pub fft_solid: Arc<AtomicBool>,')
o.append('    /// UI font index; UI-only.\n    #[persist = "ui-font"]\n    pub font: Arc<AtomicI32>,')
o.append('    /// Active user colour theme (`name|` + 36 hex digits) so a project keeps its look on a machine without the themes file.\n    #[persist = "custom-theme"]\n    pub custom_theme: Arc<parking_lot::Mutex<String>>,')
o.append('    #[persist = "preset-name"]\n    pub preset_name: Arc<parking_lot::Mutex<String>>,')
o.append('    /// Band shown on the main page (0 lo, 1 ml, 2 mh, 3 hi); UI-only.\n    #[persist = "sel-band"]\n    pub sel_band: Arc<AtomicI32>,')
for bid, _ in BANDS:
    o.append(f'    /// User-drawn waveshaper curve of the {bid} band (shaper 14); saved with the project and presets.\n    #[persist = "custom-curve-{bid}"]\n    pub curve_{bid}: Arc<parking_lot::Mutex<Vec<(f32, f32)>>>,')
for bid, _ in BANDS:
    o.append(f'    /// ASYM of the {bid} band, one value (0..100 %) per waveshaper; saved with the project and presets (absent = all 100 %).\n    #[persist = "asym-{bid}"]\n    pub asym_{bid}: Arc<parking_lot::Mutex<Vec<f32>>>,')
o.append('    /// Packed waveform-scope view settings (see gui/ui/scope.rs); UI-only, saved with the project.\n    #[persist = "scope-v3"]\n    pub scope: Arc<AtomicI32>,')
o.append('    #[persist = "match-trim"]\n    pub match_trim: Arc<AtomicF32>,')
for n, i, name, k, mn, mx, df, st, u in P:
    o.append(f'    #[id = "{i}"]\n    pub {i}: {"IntParam" if k=="int" else "BoolParam" if k=="bool" else "FloatParam"},')
o.append("}\n")
o.append("impl Default for SatXCompParams {\n    /// A new instance starts from the shared defaults file (the host then restores a saved project's own look over this).\n    fn default() -> Self {\n        Self::from_defaults(satcomp_ui::appearance::load_defaults())\n    }\n}\n")
o.append("impl SatXCompParams {\n    pub fn from_defaults(d: Option<satcomp_ui::appearance::Defaults>) -> Self {\n        Self {")
o.append("            editor_state: {\n                let (w, h) = d.as_ref().map(|d| d.size((664.0, 400.0))).unwrap_or((830, 500));\n                EguiState::from_size(w, h)\n            },")
o.append("            palette_v2: Arc::new(AtomicI32::new(d.as_ref().map(|d| d.pal_index()).unwrap_or(0))),")
o.append("            light: Arc::new(AtomicBool::new(d.as_ref().map(|d| d.light).unwrap_or(false))),")
o.append("            fft_solid: Arc::new(AtomicBool::new(d.as_ref().map(|d| d.fill_solid).unwrap_or(false))),")
o.append("            font: Arc::new(AtomicI32::new(d.as_ref().map(|d| d.face_index()).unwrap_or(0))),")
o.append("            custom_theme: Arc::new(parking_lot::Mutex::new(d.as_ref().map(|d| d.theme.clone()).unwrap_or_default())),")
o.append("            preset_name: Arc::new(parking_lot::Mutex::new(String::new())),")
o.append("            sel_band: Arc::new(AtomicI32::new(0)),")
for bid, _ in BANDS:
    o.append(f"            curve_{bid}: Arc::new(parking_lot::Mutex::new(vec![(-1.0, -1.0), (1.0, 1.0)])),")
for bid, _ in BANDS:
    o.append(f"            asym_{bid}: Arc::new(parking_lot::Mutex::new(Vec::new())),")
o.append("            scope: Arc::new(AtomicI32::new((5 << 4) | (2 << 8))),")
o.append("            match_trim: Arc::new(AtomicF32::new(0.0)),")
for n, i, name, k, mn, mx, df, st, u in P:
    if k == "int":
        o.append(f'            {i}: IntParam::new("{name}", {int(df)}, IntRange::Linear {{ min: {int(mn)}, max: {int(mx)} }}),')
    elif k == "bool":
        o.append(f'            {i}: BoolParam::new("{name}", {"true" if df else "false"}),')
    else:
        s = f'            {i}: FloatParam::new("{name}", {f(df)}, FloatRange::Linear {{ min: {f(mn)}, max: {f(mx)} }})'
        if u: s += f'.with_unit("{u}")'
        if st: s += f'.with_step_size({f(st)})'
        o.append(s + ",")
o.append("        }\n    }\n}\n")
o.append("impl SatXCompParams {")
o.append("    /// Persisted custom curve of a band (0 lo, 1 ml, 2 mh, 3 hi), sanitised.\n    pub fn curve_snapshot(&self, band: usize) -> Curve {\n        let m = [&self.curve_lo, &self.curve_mid, &self.curve_mh, &self.curve_hi][band.min(3)];\n        Curve::from_points(&m.lock())\n    }\n")
o.append("    pub fn asym_cell(&self, band: usize) -> &Arc<parking_lot::Mutex<Vec<f32>>> {\n        [&self.asym_lo, &self.asym_mid, &self.asym_mh, &self.asym_hi][band.min(3)]\n    }\n")
o.append("    /// ASYM per shaper of a band, sanitised (short / missing = 100 %).\n    pub fn asym_snapshot(&self, band: usize) -> [f64; SHAPER_COUNT] {\n        asym_from(&self.asym_cell(band).lock())\n    }\n")
o.append("    /// Snapshot for the DSP engine (UI side: may wait briefly for the curve locks).\n    pub fn to_dsp(&self) -> XParams {\n        let a = [self.asym_snapshot(0), self.asym_snapshot(1), self.asym_snapshot(2), self.asym_snapshot(3)];\n        self.to_dsp_with([self.curve_snapshot(0), self.curve_snapshot(1), self.curve_snapshot(2), self.curve_snapshot(3)], a)\n    }\n")
o.append("    /// Audio-thread snapshot: never blocks on a curve lock (the previous curve is reused while the UI holds it).\n    pub fn to_dsp_rt(&self, last: &mut [Curve; 4], last_asym: &mut [[f64; SHAPER_COUNT]; 4]) -> XParams {\n        for b in 0..4 {\n            if let Some(g) = self.asym_cell(b).try_lock() {\n                last_asym[b] = asym_from(&g);\n            }\n        }\n        for (b, m) in [&self.curve_lo, &self.curve_mid, &self.curve_mh, &self.curve_hi].into_iter().enumerate() {\n            if let Some(g) = m.try_lock() {\n                last[b] = Curve::from_points(&g);\n            }\n        }\n        self.to_dsp_with(*last, *last_asym)\n    }\n")
o.append("    fn to_dsp_with(&self, curves: [Curve; 4], asyms: [[f64; SHAPER_COUNT]; 4]) -> XParams {")
for b, (bid, _) in enumerate(BANDS):
    fl = ", ".join(
        {"bool": f"{fld[1]}: self.{bid}_{fld[1]}.value()",
         "int": f"{fld[1]}: self.{bid}_{fld[1]}.value()",
         "f": f"{fld[1]}: self.{bid}_{fld[1]}.value() as f64"}[fld[3]]
        for fld in BAND_FIELDS if fld[1] != "curve")
    o.append(f"        let {bid} = BandParams {{ curve: curves[{b}], asym: asyms[{b}], {fl} }};")
eqb = ", ".join(f"EqBandParams {{ on: self.eq{i}_on.value(), ty: self.eq{i}_type.value(), freq: self.eq{i}_freq.value() as f64, q: self.eq{i}_q.value() as f64, gain: self.eq{i}_gain.value() as f64 }}" for i in range(1, 6))
o.append(f"        let eq = EqParams {{ bands: [{eqb}], tilt: self.eq_tilt.value() as f64, pivot: self.eq_pivot.value() as f64, mix: self.eq_mix.value() as f64, gain: self.eq_gain.value() as f64, bypass: self.eq_bypass.value() }};")
o.append("        XParams {\n            x1: self.x1.value() as f64, x2: self.x2.value() as f64, x3: self.x3.value() as f64, x1_slope: self.x1_slope.value(), x2_slope: self.x2_slope.value(), x3_slope: self.x3_slope.value(), os: self.os.value(), lookahead_ms: self.lookahead.value() as f64,\n            sc_on: self.sc_on.value(), sc_gain: self.sc_gain.value() as f64, sc_hp: self.sc_hp.value() as f64, sc_lp: self.sc_lp.value() as f64, key_mix: self.sc_mix.value() as f64,\n            bands: [lo, mid, mh, hi], eq, mix: self.mix.value() as f64, out_gain: self.out_gain.value() as f64,\n            gain_match: self.gain_match.value(), bypass: self.bypass.value(), lim_on: self.lim_on.value(),\n        }\n    }\n")
o.append("    /// Parameter by UI slot number.\n    pub fn ptr(&self, n: usize) -> Option<ParamPtr> {\n        Some(match n {")
for n, i, *_ in P:
    o.append(f"            {n} => self.{i}.as_ptr(),")
o.append("            _ => return None,\n        })\n    }\n}")
o.append("\n/// Persisted per-shaper ASYM values -> the DSP array (missing / non-finite entries = 100 %, clamped to 0..100).\npub fn asym_from(v: &[f32]) -> [f64; SHAPER_COUNT] {\n    let mut a = [100.0; SHAPER_COUNT];\n    for (d, s) in a.iter_mut().zip(v) {\n        if s.is_finite() {\n            *d = (*s as f64).clamp(0.0, 100.0);\n        }\n    }\n    a\n}")
open("satxcomp-plugin/src/params.rs", "w").write("\n".join(o) + "\n")
print(len(P), "params")
